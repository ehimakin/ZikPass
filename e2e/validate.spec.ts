import { test, expect } from '@playwright/test';

const demo = { name: 'passport-copy-demo.png', mimeType: 'image/png', buffer: Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aG6kAAAAASUVORK5CYII=', 'base64') };
test('customer → verifier → customer → fingerprint check, including persistence and single selection', async ({ page }) => {
  await page.goto('/validate');
  await page.getByRole('button', { name: 'Upload document', exact: true }).click();
  await page.getByLabel('Document upload').setInputFiles(demo);
  await page.getByRole('button', { name: 'Continue →', exact: true }).click();
  await page.getByRole('combobox', { name: 'Receiving organisation', exact: true }).selectOption('northstar');
  await page.getByRole('combobox', { name: 'Document type', exact: true }).selectOption('passport-copy');
  await page.getByRole('combobox', { name: 'Jurisdiction', exact: true }).selectOption('GB-EAW');
  await page.getByRole('radio', { name: 'Certified copy', exact: true }).check();
  await page.getByRole('radio', { name: 'Not sure', exact: true }).check();
  await expect(page.getByRole('radio', { name: 'Certified copy', exact: true })).not.toBeChecked();
  await page.getByRole('button', { name: 'Continue →', exact: true }).click();
  await expect(page.getByText('Simulated analysis:')).toBeVisible();
  await page.getByRole('button', { name: 'Continue →', exact: true }).click();
  await page.getByRole('radio', { name: /Dr Maya Evans/ }).check();
  await page.getByRole('radio', { name: /Alex Morgan/ }).check();
  await expect(page.getByRole('radio', { name: /Dr Maya Evans/ })).not.toBeChecked();
  await page.getByRole('button', { name: 'Continue with selected verifier' }).click();
  await expect(page.getByText('Awaiting verifier', { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText('passport-copy-demo.png', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Switch to verifier view' }).click();
  await expect(page.getByRole('button', { name: 'Validate', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Review document', exact: true }).click();
  await expect(page.getByAltText('Uploaded document preview')).toBeVisible();
  await page.getByRole('button', { name: 'Validate', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Validate document', exact: true })).toBeDisabled();
  await page.getByRole('checkbox', { name: 'I have completed the checks described above.' }).check();
  await expect(page.getByRole('button', { name: 'Validate document', exact: true })).toBeDisabled();
  for (const checkbox of await page.getByRole('group', { name: 'Required evidence checks' }).getByRole('checkbox').all()) await checkbox.check();
  await page.getByRole('button', { name: 'Validate document', exact: true }).click();
  await expect(page.getByRole('heading', { name: '✓ ZIK VALIDATED' })).toBeVisible();
  await page.getByRole('button', { name: 'Return to customer' }).click();
  await page.getByRole('link', { name: 'View validation', exact: true }).click();
  await page.getByRole('button', { name: 'Check validation' }).click();
  await expect(page.getByRole('heading', { name: 'Validation confirmed ✓' })).toBeVisible();
  await expect(page.getByText('Document not compared yet.')).toBeVisible();
  await page.getByLabel('Compare document').setInputFiles(demo);
  await expect(page.getByText('Document unchanged · Fingerprint matches ✓')).toBeVisible();
  await page.getByLabel('Compare document').setInputFiles({ ...demo, buffer: Buffer.from('different document') });
  await expect(page.getByText('Document differs · Fingerprint does not match')).toBeVisible();
});

