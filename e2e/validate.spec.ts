test('clarification is separate from an in-person witnessing appointment', async ({ page }) => {
  await page.goto('/validate');
  await page.getByRole('button', { name: 'Upload document', exact: true }).click();
  await page.getByLabel('Document upload').setInputFiles(demo);
  await page.getByRole('button', { name: 'Continue →' }).click();
  await page.getByRole('combobox', { name: 'Receiving organisation', exact: true }).selectOption('northstar');
  await page.getByRole('combobox', { name: 'Document type', exact: true }).selectOption('consent-form');
  await page.getByRole('combobox', { name: 'Jurisdiction', exact: true }).selectOption('GB-EAW');
  await page.getByRole('radio', { name: 'Certified copy', exact: true }).check();
  await page.getByRole('button', { name: 'Continue →' }).click();
  await expect(page.getByRole('heading', { name: 'Requirements need clarification' })).toBeVisible();
  await expect(page.getByText(/requirements are unresolved, not that you need an in-person visit/)).toBeVisible();
  await page.getByRole('button', { name: 'Use witness a signature' }).click();
  await expect(page.getByRole('heading', { name: 'In-person witnessing appointment' })).toBeVisible();
  await expect(page.getByText(/Do not sign before the appointment/)).toBeVisible();
  await page.getByRole('button', { name: 'Continue →' }).click();
  await page.getByRole('radio', { name: /Alex Morgan/ }).check();
  await page.getByRole('button', { name: 'Continue with selected verifier' }).click();
  await page.getByRole('button', { name: 'Switch to verifier view' }).click();
  await page.getByRole('button', { name: 'Review document', exact: true }).click();
  await page.getByRole('button', { name: 'Validate', exact: true }).click();
  const appointment = page.getByRole('checkbox', { name: /I attended the in-person appointment/ });
  for (const checkbox of await page.getByRole('checkbox').all()) {
    if (!(await checkbox.getAttribute('type') === 'checkbox')) continue;
    if (await checkbox.evaluate(el => el.parentElement?.textContent?.includes('I attended the in-person appointment'))) continue;
    await checkbox.check();
  }
  await expect(page.getByRole('button', { name: 'Validate document', exact: true })).toBeDisabled();
  await appointment.check();
  await page.getByRole('button', { name: 'Validate document', exact: true }).click();
  await page.getByRole('button', { name: 'Return to customer' }).click();
  await expect(page.getByText('In-person checks confirmed · Simulated', { exact: true })).toBeVisible();
});
